  const byId = new Map(TOPICS.map(item => [item.id, item]));

  function topic(id) {
    return clone(byId.get(String(id || '')) || null);
  }

  function topics(query = '') {
    const q = normalize(query);
    if (!q) return TOPICS.map(clone);
    const tokens = q.split(/\s+/).filter(Boolean);
    return TOPICS.filter(item => {
      const haystack = normalize([item.label, ...(item.keywords || []), ...(item.questions || [])].join(' '));
      return tokens.every(token => haystack.includes(token));
    }).map(clone);
  }

  function compose(ids = []) {
    const selected = unique(ids.map(id => String(id || ''))).map(id => byId.get(id)).filter(Boolean);
    const source = selected.length ? selected : [byId.get('slow')];
    const merge = key => unique(source.flatMap(item => item[key] || []));
    return {
      selected: source.map(item => ({ id: item.id, label: item.label, icon: item.icon })),
      questions: merge('questions').slice(0, 10),
      checks: merge('checks').slice(0, 8),
      hooks: merge('hooks').slice(0, 7),
      phrases: merge('phrases').slice(0, 5),
      conclusion: source[source.length - 1]?.conclusion || 'Если базовых данных недостаточно — переходи к дополнительной технической проверке.'
    };
  }

  function groupTopics(groupId, query = '') {
    const allowed = new Set(topics(query).map(item => item.id));
    return TOPICS.filter(item => item.group === groupId && allowed.has(item.id)).map(clone);
  }

