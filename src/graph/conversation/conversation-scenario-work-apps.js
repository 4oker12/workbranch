  function normalizeTopicId(value) {
    return base.normalizeTopicId?.(value) || 'low_speed';
  }

  function topic(value) {
    const id = normalizeTopicId(value);
    if (id === 'other') return clone(WORK_APPS_TOPIC);
    return base.topic?.(id) || null;
  }

  function topics() {
    const source = base.topics?.() || [];
    return source.map(item => item?.id === 'other' ? clone(WORK_APPS_TOPIC) : item);
  }

  function symptomFor(topicId, symptomId) {
    const id = normalizeTopicId(topicId);
    if (id !== 'other') return base.symptom?.(id, symptomId) || null;
    const wanted = String(symptomId || '').trim();
    const found = WORK_APPS_TOPIC.variants.find(item => item.id === wanted);
    return found ? clone(found) : null;
  }

  function helperCards(node, typeId = '') {
    if (normalizeTopicId(typeId) !== 'other') return base.helperCards?.(node, typeId) || [];
    return WORK_APPS_TOPIC.questions.slice(0, 5).map((text, index) => ({
      id: `question-${index + 1}`,
      title: index === 0 ? 'Что спросить' : `Уточнение ${index + 1}`,
      icon: 'chat',
      text
    }));
  }

  function symptomLabel(type) {
    const id = typeof type === 'string' ? type : type?.id;
    return topic(id)?.label || base.symptomLabel?.(type) || '';
  }

